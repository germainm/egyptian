"""
Generates the files of the Docker image of Egyptian from docker/templates:
docker/Dockerfile, docker/config.env, docker/rootfs/usr/local/bin/entrypoint.sh
and the Supervisor configuration.

Mayan EDMS 4.12.1 removed its Docker platform templates; they are kept here,
adapted to Egyptian. The worker queues come from the code: run this script with
the Python of an Egyptian installation and the repository code, without custom
apps, after any change to the workers, the queues or mayan/literals.py:

    MAYAN_MEDIA_ROOT=$(mktemp -d) python3 docker/generer.py

Nothing is written outside the docker directory and MAYAN_MEDIA_ROOT.
"""
import ast
import os
import sys
import tempfile
from pathlib import Path

DOCKER = Path(__file__).resolve().parent
RACINE = DOCKER.parent


def config_env():
    """config.env (input of the Dockerfile) from mayan/literals.py."""
    lignes = ['# Generated by docker/generer.py from mayan/literals.py.']
    arbre = ast.parse((RACINE / 'mayan' / 'literals.py').read_text())
    for noeud in arbre.body:
        if isinstance(noeud, ast.Assign) and len(noeud.targets) == 1:
            nom = noeud.targets[0].id
            valeur = ast.literal_eval(noeud.value)
            lignes.append('{}={}'.format(nom, valeur))
    (DOCKER / 'config.env').write_text('\n'.join(lignes) + '\n')


def reglages():
    media = os.environ.get('MAYAN_MEDIA_ROOT')
    if not media or Path(media).resolve() == Path('/opt/egyptian/media').resolve():
        sys.exit('MAYAN_MEDIA_ROOT must be an empty temporary directory.')
    module = Path(tempfile.mkdtemp()) / 'docker_generer_settings.py'
    module.write_text(
        'from mayan.settings.production import *  # NOQA\n'
        'COMMON_EXTRA_APPS = ()\n'
        'DATABASES = {{"default": {{"ENGINE": "django.db.backends.sqlite3", '
        '"NAME": "{}"}}}}\n'
        'TEMPLATES[0]["DIRS"] = list(TEMPLATES[0].get("DIRS", [])) + ["{}"]\n'.format(
            Path(media) / 'generer.sqlite3', DOCKER / 'templates'
        )
    )
    sys.path.insert(0, str(module.parent))
    sys.path.insert(0, str(RACINE))
    os.environ['DJANGO_SETTINGS_MODULE'] = 'docker_generer_settings'
    os.environ['MAYAN_COMMON_EXTRA_APPS'] = '[]'


def main():
    config_env()
    reglages()

    import django
    django.setup()

    import mayan
    from mayan.apps.platforms.platform_templates import (
        PlatformTemplate, PlatformTemplateSupervisord, Variable
    )
    from mayan.apps.logging.literals import DEFAULT_LOGGING_LEVEL
    from mayan.apps.platforms.utils import load_env_file
    from mayan.apps.task_manager.classes import Worker
    from mayan import literals

    if mayan.__file__ != str(RACINE / 'mayan' / '__init__.py'):
        sys.exit('mayan is imported from {}, not from this repository.'.format(mayan.__file__))

    class Entrypoint(PlatformTemplate):
        name = 'egyptian_docker_entrypoint'
        template_name = 'entrypoint.tmpl'

        def get_context(self):
            os.chdir(DOCKER)
            context = load_env_file(skip_local_config=True)
            context.update(
                {
                    'DEFAULT_LOGGING_LEVEL': DEFAULT_LOGGING_LEVEL,
                    'MAYAN_BUILD_STRING': mayan.__build_string__,
                    'MAYAN_COPYRIGHT': mayan.__copyright__,
                    'MAYAN_FORK_COPYRIGHT': mayan.__fork_copyright__,
                    'MAYAN_LICENSE': mayan.__license__,
                    'MAYAN_TITLE': mayan.__title__,
                    'MAYAN_UPSTREAM_TITLE': mayan.__upstream_title__,
                    'MAYAN_VERSION': mayan.__version__,
                    'MAYAN_WEBSITE': mayan.__website__,
                    'SUPERVISOR_AUTORESTART': 'false',
                    'workers': Worker.all()
                }
            )
            return context

    class Supervisord(PlatformTemplateSupervisord):
        name = 'egyptian_docker_supervisord'
        template_name = 'supervisord.tmpl'

        def get_context(self):
            return {
                'stderr_logfile': '/dev/fd/2',
                'stderr_logfile_maxbytes': '0',
                'stdout_logfile': '/dev/fd/1',
                'stdout_logfile_maxbytes': '0',
                'workers': Worker.all()
            }

    class Dockerfile(PlatformTemplate):
        name = 'egyptian_docker_dockerfile'
        template_name = 'dockerfile.tmpl'

        def __init__(self):
            self.variables = (
                Variable(
                    name='DOCKER_LINUX_IMAGE_NAME',
                    default=literals.DOCKER_LINUX_IMAGE_NAME,
                    environment_name='MAYAN_DOCKER_LINUX_IMAGE_NAME'
                ),
                Variable(
                    name='DOCKER_LINUX_IMAGE_TAG',
                    default=literals.DOCKER_LINUX_IMAGE_TAG,
                    environment_name='MAYAN_DOCKER_LINUX_IMAGE_TAG'
                ),
            )

        def get_context(self):
            return {
                name: getattr(literals, name) for name in (
                    'DOCKER_USER_GID', 'DOCKER_USER_UID', 'DOCKER_USER_USERNAME',
                    'LINUX_PACKAGES_DEBIAN_BASE', 'LINUX_PACKAGES_DEBIAN_BUILD',
                    'LINUX_PACKAGES_DEBIAN_MYSQL', 'LINUX_PACKAGES_DEBIAN_POSTGRESQL',
                    'LINUX_PACKAGES_DEBIAN_PYTHON'
                )
            }

    sorties = {
        DOCKER / 'Dockerfile': Dockerfile,
        DOCKER / 'rootfs' / 'usr' / 'local' / 'bin' / 'entrypoint.sh': Entrypoint,
        DOCKER / 'rootfs' / literals.SUPERVISOR_CONFIGURATION_DIRECTORY.strip('/') / literals.SUPERVISOR_CONFIGURATION_FILENAME: Supervisord,
    }
    for chemin, classe in sorties.items():
        chemin.parent.mkdir(parents=True, exist_ok=True)
        chemin.write_text(classe().render().rstrip('\n') + '\n')
        print('written', chemin.relative_to(RACINE))
    (DOCKER / 'rootfs' / 'usr' / 'local' / 'bin' / 'entrypoint.sh').chmod(0o755)
    print('workers:', ', '.join(
        '{} ({})'.format(w.name, ','.join(q.name for q in w.queues)) for w in Worker.all()
    ))


if __name__ == '__main__':
    main()
